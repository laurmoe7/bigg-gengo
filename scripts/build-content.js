// Builds renderer/content.js from scripts/content-src.js: adds readings and word splits (kuromoji, a dev dependency) to every Japanese line.
//   node scripts/build-content.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const kuromoji = require('kuromoji');
const src = require('./content-src.js');
const kata2hira = (s) => s.replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));
const CONTENT = ['名詞', '動詞', '形容詞', '副詞', '連体詞', '感動詞'];

kuromoji.builder({ dicPath: path.join(__dirname, '..', 'node_modules', 'kuromoji', 'dict') }).build((err, tk) => {
  if (err) throw err;
  // "surface;reading;basicForm|..." like the sentences in data/sentences.js
  const tok = (s) => tk.tokenize(s).map((t) => {
    const sf = t.surface_form, rd = t.reading && t.reading !== '*' ? kata2hira(t.reading) : sf;
    const content = CONTENT.includes(t.pos) && t.pos_detail_1 !== '非自立' && t.pos_detail_1 !== '接尾' && t.pos_detail_1 !== '数';
    const basic = content && t.basic_form && t.basic_form !== '*' && t.basic_form !== sf ? t.basic_form : '';
    return rd === sf && !basic ? sf : sf + ';' + (rd === sf ? '' : rd) + (basic ? ';' + basic : '');
  }).join('|');
  const kana = (s) => tk.tokenize(s).map((t) => (t.reading && t.reading !== '*' ? kata2hira(t.reading) : t.surface_form)).join('');
  const POS = { n: 'noun', v: 'verb', a: 'adjective', o: 'other' };
  const warn = [];

  const SEED_WORDS = src.SEED_WORDS.map(([ja, reading, en, kind, cls, example, exampleEn]) => {
    if (!tk.tokenize(example).some((t) => t.surface_form.includes(ja.replace(/[るうくぐすつぬぶむい]$/, '').slice(0, 2)) || t.basic_form === ja)) warn.push('example may not contain ' + ja + ': ' + example);
    return { ja, reading, en, pos: POS[kind], vclass: cls, example, exampleEn, exTok: tok(example) };
  });
  const PROVERBS = src.PROVERBS.map(([ja, en]) => [ja, en, tok(ja)]);
  const PHRASES = src.PHRASES.map(([cat, ja, en, fill]) => {
    if (fill && !ja.includes(fill)) warn.push('fill word ' + fill + ' is not in ' + ja);
    return [cat, ja, en, fill || '', tok(ja)];
  });
  const DAILY_PHRASES = src.PHRASES.filter((p) => ['hello', 'want', 'talk', 'home', 'way'].includes(p[0]) && [...p[1]].length >= 7).slice(0, 36).map(([, ja, en]) => [ja, en, tok(ja)]);
  const PH_PATTERNS = src.PH_PATTERNS.map((p) => {
    const [before, after] = p.ja.split('{}');
    return { ja: p.ja, en: p.en, frameR: [kana(before), kana(after)], swaps: p.swaps.map(([ja, en]) => [ja, en, kana(ja)]) };
  });
  // Furigana for the Grammar cheat sheets (renderer/seed.js): per sheet, per paragraph, [offset in the text without tags, kanji, reading].
  // The counters sheet writes its readings out already. kuromoji misreads a few words here, so those are fixed by hand (with the text that follows).
  const J = require('../renderer/japanese.js');
  const GRAMMAR = vm.runInNewContext(fs.readFileSync(path.join(__dirname, '..', 'renderer', 'seed.js'), 'utf8') + '\n;GRAMMAR', { SEED_WORDS: [] });
  const FIX = (s, next) => ({ 日本: 'にほん', 日本語: 'にほんご', 行っ: 'いっ', 千: 'せん', 万: 'まん' }[s]
    || (s === '来' ? (/^る/.test(next) ? 'く' : /^[なよさ]/.test(next) ? 'こ' : 'き') : '')
    || (/^時/.test(next) ? { 四: 'よ', 七: 'しち', 九: 'く' }[s] : ''));
  const GRAMMAR_RUBY = GRAMMAR.map((g) => g.b.map((p) => {
    if (/^Numbers/.test(g.t)) return [];
    const plain = p.replace(/<[^>]+>/g, ''), out = [];
    let at = 0;
    for (const t of tk.tokenize(plain)) {
      const s = t.surface_form, start = plain.indexOf(s, at); at = start + s.length;
      if (!J.hasKanji(s)) continue;
      const rd = FIX(s, plain.slice(at)) || (t.reading && t.reading !== '*' ? kata2hira(t.reading) : '');
      if (!rd) { warn.push('no reading for ' + s + ' in: ' + g.t); continue; }
      let off = start;
      for (const [seg, r] of J.ruby(s, rd)) { if (r) out.push([off, seg, r]); off += seg.length; }
    }
    return out;
  }));
  const out = '// Generated by scripts/build-content.js from scripts/content-src.js (readings and word splits from kuromoji). Do not edit by hand.\n' +
    'const SEED_WORDS = ' + JSON.stringify(SEED_WORDS) + ';\n' +
    '// [japanese, english, words]\nconst PROVERBS = ' + JSON.stringify(PROVERBS) + ';\n' +
    '// Phrasebook for the Phrases tab: [category, japanese, english, word to hide in "fill the blank" (or \'\'), words]\n' +
    'const PH_CATS = ' + JSON.stringify(src.PH_CATS) + ';\nconst PHRASES = ' + JSON.stringify(PHRASES) + ';\n' +
    '// Two phrases show up on Today each day (chosen from the date)\nconst DAILY_PHRASES = ' + JSON.stringify(DAILY_PHRASES) + ';\n' +
    '// A sentence frame with a {} gap, its English, the kana before and after the gap, and the words that fit: [japanese, english, reading]\nconst PH_PATTERNS = ' + JSON.stringify(PH_PATTERNS) + ';\n' +
    '// Furigana for the Grammar cheat sheets in seed.js: per sheet, per paragraph, [offset in the text without tags, kanji, reading]\nconst GRAMMAR_RUBY = ' + JSON.stringify(GRAMMAR_RUBY) + ';\n';
  fs.writeFileSync(path.join(__dirname, '..', 'renderer', 'content.js'), out);
  console.log('words', SEED_WORDS.length, '| proverbs', PROVERBS.length, '| phrases', PHRASES.length, '| daily', DAILY_PHRASES.length, '| patterns', PH_PATTERNS.length);
  warn.forEach((w) => console.log('WARN', w));
});
